<script setup lang="ts">
import { ref, onMounted } from "vue";
import ReCol from "@/components/ReCol";
import { useDark } from "./utils";
import { ReNormalCountTo } from "@/components/ReCountTo";
import { ChartBar, ChartLine, ChartRound } from "./components/charts";
import { useApiData, progressData } from "./data";
import { getUserApiStats } from "@/api/system/consumer";

defineOptions({
  name: "UserPanel"
});

const { isDark } = useDark();
const { chartData, onSearch } = useApiData();

const barChartData = ref({
  chartData: []
});

// 在组件挂载时获取数据
onMounted(async () => {
  await onSearch();
  await fetchBarChartData();
});

async function fetchBarChartData() {
  try {
    const { data } = await getUserApiStats();
    barChartData.value = {
      chartData: data
    };
  } catch (error) {
    console.error("Failed to fetch bar chart data:", error);
  }
}
</script>

<template>
  <div>
    <el-row :gutter="24" justify="space-around">
      <re-col
        v-for="(item, index) in chartData"
        :key="index"
        v-motion
        class="mb-[18px]"
        :value="6"
        :md="12"
        :sm="12"
        :xs="24"
        :initial="{
          opacity: 0,
          y: 100
        }"
        :enter="{
          opacity: 1,
          y: 0,
          transition: {
            delay: 80 * (index + 1)
          }
        }"
      >
        <el-card class="line-card" shadow="never">
          <div class="flex justify-between">
            <span class="text-md font-medium">
              {{ item.name }}
            </span>
            <div
              class="w-8 h-8 flex justify-center items-center rounded-md"
              :style="{
                backgroundColor: isDark ? 'transparent' : item.bgColor
              }"
            >
              <IconifyIconOffline
                :icon="item.icon"
                :color="item.color"
                width="18"
              />
            </div>
          </div>
          <div class="flex justify-between items-start mt-3">
            <div class="w-1/2">
              <!-- 根据类型判断显示方式 -->
              <template v-if="Array.isArray(item.value)">
                <div class="text-[1.2em] mt-6">
                  <span v-for="(role, index) in item.value" :key="index">
                    {{ role }}{{ index !== item.value.length - 1 ? "," : "" }}
                  </span>
                </div>
              </template>
              <template v-else>
                <ReNormalCountTo
                  :duration="item.duration"
                  :fontSize="'1.6em'"
                  :startVal="100"
                  :endVal="item.value"
                />
              </template>
              <p class="font-medium text-green-500">{{ item.percent }}</p>
            </div>
            <ChartLine
              v-if="item.data.length > 1"
              class="!w-1/2"
              :color="item.color"
              :data="item.data"
            />
            <ChartRound v-else class="!w-1/2" />
          </div>
        </el-card>
      </re-col>

      <re-col
        v-motion
        class="mb-[18px]"
        :value="18"
        :xs="24"
        :initial="{
          opacity: 0,
          y: 100
        }"
        :enter="{
          opacity: 1,
          y: 0,
          transition: {
            delay: 400
          }
        }"
      >
        <el-card class="bar-card" shadow="never">
          <div class="flex justify-between">
            <span class="text-md font-medium">请求数据</span>
          </div>
          <div class="flex justify-between items-start mt-3">
            <ChartBar :chartData="barChartData.chartData" />
          </div>
        </el-card>
      </re-col>

      <re-col
        v-motion
        class="mb-[18px]"
        :value="6"
        :xs="24"
        :initial="{
          opacity: 0,
          y: 100
        }"
        :enter="{
          opacity: 1,
          y: 0,
          transition: {
            delay: 480
          }
        }"
      >
        <el-card shadow="never">
          <div class="flex justify-between">
            <span class="text-md font-medium">解决概率</span>
          </div>
          <div
            v-for="(item, index) in progressData"
            :key="index"
            :class="[
              'flex',
              'justify-between',
              'items-start',
              index === 0 ? 'mt-8' : 'mt-[2.15rem]'
            ]"
          >
            <el-progress
              :text-inside="true"
              :percentage="item.percentage"
              :stroke-width="21"
              :color="item.color"
              striped
              striped-flow
              :duration="item.duration"
            />
            <span class="text-nowrap ml-2 text-text_color_regular text-sm">
              {{ item.week }}
            </span>
          </div>
        </el-card>
      </re-col>
    </el-row>
  </div>
</template>

